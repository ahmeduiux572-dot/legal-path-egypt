export const libraryBooks: LibraryBook[] = rawBooks.map((b) => ({
  ...b,
  articlesCount: countArticles(b.chapters),
}));

export function getLibraryBook(id: string): LibraryBook | undefined {
  return libraryBooks.find((b) => b.id === id);
}

/** بحث نصّي داخل عناوين الكتب والوسوم والمواد */
export function searchLibrary(query: string): LibraryBook[] {
  const q = query.trim();
  if (!q) return libraryBooks;
  return libraryBooks.filter(
    (b) =>
      b.title.includes(q) ||
      b.description.includes(q) ||
      b.authority.includes(q) ||
      b.tags.some((t) => t.includes(q)) ||
      b.chapters.some((c) =>
        c.articles.some((a) => a.text.includes(q) || a.num === q),
      ),
  );
}